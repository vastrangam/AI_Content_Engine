/* THE STARTER KIT — an archive a coding agent can actually build from.
 *
 *   node brand/delivery/website/mkstarter.js            → MEDHAVA_STARTER.zip
 *   node brand/delivery/website/mkstarter.js --verify   → the same, then EXTRACT IT AND RUN IT
 *
 * WHY THIS EXISTS, AND WHY IT IS NOT MEDHAVA.zip
 * The delivery archives carry documents. That is what they are for, and it is why mkall.js opens
 * by saying they cannot build anything — a claim that was not a guess: extracting one and testing
 * the build prompt against it found 18 of its 22 paths absent and every command in it broken. A
 * document describes software. It does not produce it.
 *
 * This archive carries the REPOSITORY: the schema, the registers, the gates, the tests, the
 * toolchain lockfile, the working platform slice, and the working agreement that governs how they
 * are changed. An agent handed this has the thing the documents are about.
 *
 * THE ONE HONEST TEST OF A BUILD ARCHIVE IS TO BUILD FROM IT.
 * So --verify does not inspect the file list and conclude. It unzips into a scratch directory
 * nowhere near this repository, installs the toolchain, and runs the suite from the extract. What
 * it prints is that run's real exit code. Anything less is the same mistake in a new archive: an
 * assurance that the contents look right, which is exactly what was believed the last time.
 *
 * WHAT IS DELIBERATELY LEFT OUT
 *   node_modules   restored by `npm ci` from the committed lockfile, which is the point of a
 *                  lockfile. Shipping it would multiply the archive and pin one machine's
 *                  platform binaries.
 *   *.pdf          365MB of RENDERED documents, all regenerated by tools/report_pdf.py from
 *                  markdown that is in here. An agent reads the markdown.
 *   *.zip          202MB of archives, including this one's own siblings. An archive of archives.
 *   *.docx         one research file with no build role.
 *   ONE .html      the single rendered document among 72 tracked .html files. The other 71 are
 *                  source and stay — see isRenderedDocument() for why that is a rule and not a
 *                  list, and for what dropping all of them did.
 * Every exclusion is a thing that is DERIVED from something included, which is the test for
 * whether leaving it out loses anything.
 *
 * THE FILE LIST COMES FROM GIT, NOT A WALK.
 * `git ls-files` returns exactly what is committed — so nothing gitignored can be swept in, and
 * app/.env, app/data/ and every build artifact are excluded by construction rather than by a
 * pattern somebody has to remember to update. CLAUDE.md §4 requires that keys never reach an
 * artifact; this makes it structural instead of careful.
 */

const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { execFileSync, execSync } = require('node:child_process');

const ROOT = path.join(__dirname, '..', '..', '..');
const OUT = path.join(ROOT, 'MEDHAVA_STARTER.zip');
const STAGE = path.join(os.tmpdir(), 'medhava-starter-stage');

const verify = process.argv.includes('--verify');

const MODULES = require(path.join(ROOT, 'brand', 'site', 'modules.js'));
const RULES = require(path.join(ROOT, 'brand', 'site', 'rules.js'));
const PKG = JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8'));

/* Derived, never typed — the counts in the document this writes have already changed twice.
 *
 * AND A COUNT THAT CANNOT BE DERIVED STOPS THE BUILD. The first version of this reached for
 * RULES.RULES and RULES.ALL, found neither (rules.js exports the array itself), fell through to a
 * `|| 0` and printed "0 rules" into a document meant to tell somebody where the rulebook is.
 * Silently substituting zero for "I could not read it" is worse than typing the number, because a
 * typed number is at least wrong loudly. */
function derived(what, n) {
  if (!Number.isInteger(n) || n <= 0) {
    console.error(`mkstarter: could not derive ${what} — refusing to write a document that ` +
      `states a count it did not read. Fix the derivation, do not type the number.`);
    process.exit(1);
  }
  return n;
}

const NMODULES = derived('the module count', MODULES.length);
const NAPPS = derived('the app count', MODULES.reduce((n, m) => n + m.apps.length, 0));
const NRULES = derived('the rule count', Array.isArray(RULES) ? RULES.length : NaN);
const NTABLES = derived('the table count',
  (fs.readFileSync(path.join(ROOT, 'core', 'schema.postgres.sql'), 'utf8')
    .match(/^CREATE TABLE /gm) || []).length);

/* ── what goes in ────────────────────────────────────────────────────────── */

/* .html IS NOT A DOCUMENT FORMAT HERE, AND ASSUMING IT WAS BROKE THE ARCHIVE.
 * The first version dropped every .html alongside the .pdf and .zip output. That deleted
 * medhava/web/index.html — the application's own page — so the extracted archive served a 404
 * where the shell should be, and the browser suite failed five checks with confusing downstream
 * messages. It also deleted the 16 built prototype apps under brand/suite/out/.
 *
 * Of the 72 tracked .html files, exactly ONE is a rendered document. The rule that separates them
 * is not a list to maintain: a rendered document has a sibling .md of the same name, because that
 * is literally what tools/report_pdf.py made it from. Everything else is source. */
function isRenderedDocument(f) {
  if (!/\.html$/i.test(f)) return false;
  return fs.existsSync(path.join(ROOT, f.replace(/\.html$/i, '.md')));
}
const DROP = /\.(pdf|zip|docx)$/i;

function contents() {
  const tracked = execSync('git ls-files -z', { cwd: ROOT, maxBuffer: 64 * 1024 * 1024 })
    .toString('utf8').split('\0').filter(Boolean);
  return tracked.filter((f) => !DROP.test(f) && !isRenderedDocument(f));
}

