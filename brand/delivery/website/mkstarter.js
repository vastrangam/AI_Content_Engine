/* ── the gate ────────────────────────────────────────────────────────────── */

function badCommand(cmd, has) {
  const parts = cmd.trim().split('\n')[0].trim().split(/\s+/);
  const [bin, a, b] = parts;
  if (bin === 'npm') {
    if (['ci', 'install', 'start', 'test'].includes(a)) return null;
    const script = a === 'run' ? b : a;
    if (!script) return 'names no npm script';
    return script in (PKG.scripts || {}) ? null : `npm script "${script}" is not in package.json`;
  }
  if (bin === 'node' || bin === 'python3') {
    if (!a) return `${bin} with no file`;
    return has.has(a) ? null : `${a} is not in the archive`;
  }
  if (bin === 'cd') return null;
  return null;
}

/** Every path and command the starter's own documents name must be IN the archive. */
function gate(files) {
  const has = new Set(files);
  const bad = [];

  /* The documents an agent is pointed at first. A path named in one of these that is not in the
     archive is the exact defect that made the document bundle unbuildable. */
  const speaks = ['START_HERE.md', 'CLAUDE.md', 'MEDHAVA_BOS_PROMPT.md'];
  for (const doc of speaks) {
    const text = doc === 'START_HERE.md' ? startHere()
      : has.has(doc) ? fs.readFileSync(path.join(ROOT, doc), 'utf8') : null;
    if (text === null) { bad.push(`${doc} is not in the archive`); continue; }

    /* Backticked things that look like repository paths — a slash and a known extension, or a
       bare directory. Deliberately narrow: a regex that guesses widely reports noise, and a gate
       that cries wolf gets switched off. */
    const cited = new Set([...text.matchAll(/`([A-Za-z0-9_./-]+\.(?:js|py|sql|json|md))`/g)]
      .map((m) => m[1]).filter((p) => p.includes('/') || has.has(p)));
    for (const p of cited) {
      if (!has.has(p)) bad.push(`${doc} names \`${p}\`, which is not in the archive`);
    }

    for (const m of text.matchAll(/```bash\n([\s\S]*?)```/g)) {
      for (const line of m[1].split('\n')) {
        const cmd = line.replace(/#.*$/, '').trim();
        if (!cmd) continue;
        const why = badCommand(cmd, has);
        if (why) bad.push(`${doc}: "${cmd}" — ${why}`);
      }
    }
  }

  /* The things without which nothing can be built at all, named individually so the failure says
     which one rather than "something is missing". */
  const MUST = [
    ['core/schema.postgres.sql', 'the database'],
    ['brand/site/modules.js', 'the canonical module list'],
    ['brand/site/rules.js', 'the rulebook'],
    ['package.json', 'the scripts'],
    ['package-lock.json', 'the toolchain, reproducibly'],
    ['CLAUDE.md', 'the working agreement'],
    ['medhava/server/db.js', 'the isolation the whole platform rests on'],
    ['medhava/test/isolation.test.js', 'the worked example of red-before-green'],
  ];
  for (const [p, why] of MUST) {
    if (!has.has(p)) bad.push(`${p} is missing — ${why}`);
  }

  /* Every npm script the starter tells somebody to run must name files that are present. */
  for (const [name, cmd] of Object.entries(PKG.scripts || {})) {
    for (const piece of cmd.split('&&')) {
      const why = badCommand(piece.trim(), has);
      if (why) bad.push(`npm script "${name}" runs "${piece.trim()}" — ${why}`);
    }
  }

  /* AND THE TWO CHECK SCRIPTS MUST NOT DRIFT.
     `check:source` exists for one reason: this archive ships no rendered PDFs, so checkcoverage —
     which gates DELIVERED DOCUMENTS against their PDFs — has nothing to gate and fails on all ten.
     It is the delivery gate, not a build gate. The danger is obvious: two lists of checks, and the
     next check added to one and not the other is silently not run by whoever uses this archive.
     So the relationship is asserted rather than trusted — `check:source` must be exactly `check`
     with checkcoverage removed, and nothing else. */
  const full = (PKG.scripts || {})['check'] || '';
  const src = (PKG.scripts || {})['check:source'] || '';
  const expected = full.split('&&').map((s) => s.trim())
    .filter((s) => !/checkcoverage\.js/.test(s)).join(' && ');
  if (src !== expected) {
    bad.push('npm "check:source" is not "check" minus checkcoverage. One of them has gained a ' +
      'check the other has not, and this archive would ship running the smaller list.\n' +
      `      expected: ${expected}\n      found:    ${src}`);
  }
  if (!/checkcoverage\.js/.test(full)) {
    bad.push('npm "check" no longer runs checkcoverage — then check:source has no reason to ' +
      'exist and the delivered documents are ungated. Delete one or restore the other.');
  }
  return bad;
}

/* ── build ───────────────────────────────────────────────────────────────── */

function stage(files) {
  fs.rmSync(STAGE, { recursive: true, force: true });
  const root = path.join(STAGE, 'medhava-bos');
  for (const f of files) {
    const dest = path.join(root, f);
    fs.mkdirSync(path.dirname(dest), { recursive: true });
    fs.copyFileSync(path.join(ROOT, f), dest);
  }
  fs.writeFileSync(path.join(root, 'START_HERE.md'), startHere());
  return root;
}

function main() {
  const files = contents();
  const bad = gate([...files, 'START_HERE.md']);
  if (bad.length) {
    console.error(`mkstarter: ${bad.length} problem(s) — this archive would not build:\n  ` +
      bad.join('\n  '));
    process.exit(1);
  }

  const root = stage(files);
  fs.rmSync(OUT, { force: true });
  execFileSync('zip', ['-qr', OUT, 'medhava-bos'], { cwd: STAGE, maxBuffer: 64 * 1024 * 1024 });

  const mb = (fs.statSync(OUT).size / 1024 / 1024).toFixed(1);
  console.log(`MEDHAVA_STARTER.zip written: ${mb}MB · ${files.length + 1} files`);
  console.log(`  ${NMODULES} modules · ${NAPPS} apps specified · ${NTABLES} tables · ` +
              `${NRULES} rules — every count read from source`);
  console.log(`  gate: every path and command in START_HERE, CLAUDE.md and the build prompt ` +
              `exists in the archive`);

  if (!verify) {
    console.log('\n  Run with --verify to extract it somewhere else and actually run the suite.');
    return;
  }

  /* ── the only test that means anything ─────────────────────────────────── */
  const box = fs.mkdtempSync(path.join(os.tmpdir(), 'starter-verify-'));
  console.log(`\n  verifying by extraction into ${box}`);
  execFileSync('unzip', ['-q', OUT, '-d', box]);
  const extracted = path.join(box, 'medhava-bos');

  /* npm ci needs the registry. Where it cannot be reached, the lockfile is still the right answer
     and the local install is a stand-in for it — but say which one happened, because "it built"
     means something different in each case. */
  let install = 'npm ci';
  try {
    execFileSync('npm', ['ci', '--no-audit', '--no-fund'],
      { cwd: extracted, stdio: 'pipe', timeout: 900000 });
  } catch (e) {
    install = 'copied node_modules (no registry reachable)';
    fs.cpSync(path.join(ROOT, 'node_modules'), path.join(extracted, 'node_modules'),
      { recursive: true });
  }
  console.log(`  toolchain: ${install}`);

  let code = 0, out = '';
  try {
    out = execFileSync('npm', ['run', 'test:source'],
      { cwd: extracted, encoding: 'utf8', timeout: 2400000 });
  } catch (e) { code = e.status === undefined ? 1 : e.status; out = (e.stdout || '') + (e.stderr || ''); }

  const tail = out.trim().split('\n').slice(-14).join('\n    ');
  console.log(`\n    ${tail}`);
  console.log(`\n  npm run test:source in the EXTRACTED archive: exit ${code}`);
  if (code === 0) {
    console.log('  The archive builds. Not inspected — extracted, installed and run.');
  } else {
    console.log('  The archive does NOT build. Fix that before sending it to anybody.');
  }
  process.exit(code);
}

main();
